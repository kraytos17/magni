"""Minimize a seed corpus: cmin → monster purge → rewrite promoted set.

Parser pool regenerates fuzz/corpus/promoted_seeds.py; exec pool
(`corpus minimize --exec`) regenerates fuzz/corpus_exec/promoted_seeds.py.
Hand seeds in the generator scripts are never touched. Aborts (leaving
everything unchanged) if tuple coverage would drop.
"""

import importlib.util
import re
import shutil
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from . import config
from .cmin import afl_cmin
from .corpus import corpus_generate, stage_corpus_into
from .showmap import showmap_tuples
from .util import die, log


def cmin_to_tmp(pool: config.CorpusPool) -> tuple[Path, Path, list[str]]:
    """Stage + afl-cmin into a temp dir. Returns (tmpdir, min_dir, kept)."""
    from .build import ensure_cov_target, ensure_exec_target

    if pool.is_exec:
        ensure_exec_target()
    else:
        ensure_cov_target()
    tmpdir = Path(tempfile.mkdtemp(prefix="magni_minimize_"))
    staged = tmpdir / "staged"
    staged.mkdir()
    stage_corpus_into(pool.corpus_dir, staged)
    min_dir = tmpdir / "min"
    kept = afl_cmin(staged, min_dir, pool.cmin_timeout_ms, pool.cmin_target)
    return tmpdir, min_dir, kept


def purge_monsters(
    min_dir: Path, kept: list[str], baseline: int, pool: config.CorpusPool
) -> list[str]:
    """Drop oversized non-guard seeds; abort if coverage would drop."""
    # deep_* guard seeds are deliberate (MAX_PARSE_NESTING paths) and
    # always regenerated — never purge them (parser pool only; the exec
    # pool has no deep_ seeds so the guard never fires there).
    monsters = [
        n
        for n in kept
        if not n.startswith("deep_") and (min_dir / n).stat().st_size > config.MONSTER_SIZE_CAP
    ]
    final = [n for n in kept if n not in monsters]
    log(f"  dropped {len(monsters)} files over {config.MONSTER_SIZE_CAP} bytes")
    if monsters:
        check_dir = Path(tempfile.mkdtemp(prefix="magni_verify_"))
        try:
            for n in final:
                shutil.copy2(min_dir / n, check_dir / n)
            kept_tuples = showmap_tuples(check_dir, pool.cmin_target)
        finally:
            shutil.rmtree(check_dir, ignore_errors=True)
        if kept_tuples is None:
            die("verification showmap failed; aborting")
        lost = baseline - kept_tuples
        if lost > 0:
            die(
                f"monster purge would lose {lost} tuples; aborting "
                f"(tmin the monsters manually instead)"
            )
        log(f"  verified: {kept_tuples}/{baseline} tuples, 0 loss")
    return final


def rewrite_promoted_seeds(
    final: list[str], kept_total: int, baseline: int, pool: config.CorpusPool
) -> None:
    """Rewrite promoted_seeds.py from the keep-set (verified against disk)."""
    promoted_path = pool.promoted_path
    kept_set = set(final)
    kept_entries = []
    for line in promoted_path.read_text(encoding="utf-8").split("\n"):
        m = re.match(r'^    \("([^"]+)",', line)
        if m:
            if m.group(1) in kept_set:
                kept_entries.append(line)
        else:
            # header/footer lines are regenerated below; skip them
            pass
    # Sanity: every kept promoted_* name must resolve to an entry
    disk_promoted = sorted(n for n in final if n.startswith("promoted_"))
    entry_names = sorted(re.match(r'^    \("([^"]+)",', ln).group(1) for ln in kept_entries)
    if disk_promoted != entry_names:
        log("keep-set/entry mismatch; aborting without changes")
        log(f"  on disk: {len(disk_promoted)}, in file: {len(entry_names)}")
        sys.exit(1)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    table_name = "EXEC_PROMOTED" if pool.is_exec else "PROMOTED_SEEDS"
    gen_cmd = (
        "python3 magni.py corpus minimize --exec"
        if pool.is_exec
        else "python3 magni.py corpus minimize"
    )
    promote_cmd = (
        "python3 magni.py corpus promote --exec"
        if pool.is_exec
        else "python3 magni.py corpus promote"
    )
    hand_note = (
        f"({kept_total} files incl. hand scripts on disk)"
        if pool.is_exec
        else f"({kept_total} files incl. hand seeds on disk)"
    )
    header = (
        f'"""Fuzzer-grown {"exec seed scripts" if pool.is_exec else "seed corpus"} (minimized).\n\n'
        f"Generated by: {gen_cmd}\n"
        f"Last minimized: {stamp}\n"
        f"Seeds: {len(kept_entries)} promoted {hand_note}\n"
        f"Basis: afl-cmin + monster purge "
        f"(>{config.MONSTER_SIZE_CAP} bytes dropped)\n"
        f"Coverage verified: {baseline}/{baseline} tuples, 0 loss.\n\n"
        f"Do not hand-edit. To regenerate after a campaign, run\n"
        f"`{promote_cmd}` (appends new finds) then\n"
        f"`{gen_cmd}` again.\n"
        f'"""\n\n{table_name} = [\n'
    )
    promoted_path.write_text(
        header + "".join(ln + "\n" for ln in kept_entries) + "]\n", encoding="utf-8"
    )
    log(f"  wrote {len(kept_entries)} entries to {promoted_path}")


def regenerate_and_drop_stale(pool: config.CorpusPool) -> None:
    """Regenerate corpus from updated sources; remove minimized-away seeds."""
    log("Regenerating corpus from updated sources...")
    corpus_generate(exec_scripts=pool.is_exec)
    # The generator only removes files it knows about; drop stale seeds
    # left behind by the minimization (names no longer in the tables).
    sys.path.insert(0, str(pool.corpus_dir))
    try:
        spec = importlib.util.spec_from_file_location(pool.gen_script.stem, str(pool.gen_script))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    finally:
        sys.path.remove(str(pool.corpus_dir))
    live = set(config.DEEP_GUARD_SEEDS) | {
        pool.gen_script.name,
        "promoted_seeds.py",
        "__pycache__",
    }
    for table in pool.seed_tables:
        live |= {name for name, _ in getattr(mod, table)}
    stale = [f.name for f in pool.corpus_dir.iterdir() if f.is_file() and f.name not in live]
    for name in stale:
        (pool.corpus_dir / name).unlink()
    if stale:
        log(f"  removed {len(stale)} stale {pool.label}s")
    gate = "corpus test --exec" if pool.is_exec else "corpus test"
    log(f"Done. Run `python3 magni.py {gate}` for the ASan gate.")


def corpus_minimize(exec_pool: bool = False) -> None:
    pool = config.EXEC_POOL if exec_pool else config.PARSER_POOL
    tmpdir = None
    try:
        log("[1/4] Baseline tuple count...")
        baseline = showmap_tuples(pool.corpus_dir, pool.cmin_target)
        if baseline is None:
            die("baseline showmap failed; aborting")
        log(f"  baseline: {baseline} tuples")

        log("[2/4] Minimizing with afl-cmin...")
        tmpdir, min_dir, kept = cmin_to_tmp(pool)
        log(f"  cmin: {len(kept)} files kept")

        log("[3/4] Purging monsters...")
        final = purge_monsters(min_dir, kept, baseline, pool)

        log("[4/4] Rewriting promoted_seeds.py...")
        rewrite_promoted_seeds(final, len(kept), baseline, pool)
    finally:
        if tmpdir is not None:
            shutil.rmtree(tmpdir, ignore_errors=True)

    regenerate_and_drop_stale(pool)
